// שעה עשרונית לתצוגה: 13.5 → "13:30".
const hm = (hour) => `${Math.floor(hour)}:${String(Math.round((hour % 1) * 60)).padStart(2, "0")}`;

// "ראשון–חמישי 9:00–19:00" — מקבץ ימים רצופים בעלי אותן שעות לשורה אחת.
const hoursLines = () => {
  const runs = [];
  week.forEach((day, index) => {
    if (!day) return;
    const last = runs.at(-1);
    if (last && last.to === index - 1 && last.open === day.open && last.close === day.close) {
      last.to = index;
      return;
    }
    runs.push({ from: index, to: index, open: day.open, close: day.close });
  });
  return runs.map(({ from, to, open, close }) => {
    const days = from === to ? DAY_NAMES[from] : `${DAY_NAMES[from]}–${DAY_NAMES[to]}`;
    return `${days} ${hm(open)}–${hm(close)}`;
  });
};

